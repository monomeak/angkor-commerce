CREATE TABLE invoices (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number          VARCHAR(50) NOT NULL,
    customer_id             BIGINT NOT NULL,

    invoice_status          VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    status                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    issue_date              DATE NOT NULL,
    due_date                DATE NOT NULL,

    subtotal                NUMERIC(19, 4) NOT NULL DEFAULT 0,
    discount_percentage     NUMERIC(5, 2) NOT NULL DEFAULT 0,
    discount_amount         NUMERIC(19, 4) NOT NULL DEFAULT 0,
    tax_percentage          NUMERIC(5, 2) NOT NULL DEFAULT 0,
    tax_amount              NUMERIC(19, 4) NOT NULL DEFAULT 0,
    total                   NUMERIC(19, 4) NOT NULL DEFAULT 0,
    paid_amount             NUMERIC(19, 4) NOT NULL DEFAULT 0,
    balance                 NUMERIC(19, 4) NOT NULL DEFAULT 0,

    currency                CHAR(3) NOT NULL DEFAULT 'KHR',
    total_items             INTEGER NOT NULL DEFAULT 0,
    total_quantity          INTEGER NOT NULL DEFAULT 0,

    notes                   TEXT,
    issued_at               TIMESTAMPTZ,
    cancelled_at            TIMESTAMPTZ,
    cancellation_reason     TEXT,

    created_by_user_id      BIGINT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_invoices_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_invoices_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES users (id)
        ON DELETE SET NULL,

    CONSTRAINT uq_invoices_invoice_number
        UNIQUE (invoice_number),

    CONSTRAINT chk_invoices_invoice_status
        CHECK (
            invoice_status IN (
                'DRAFT',
                'ISSUED',
                'PARTIALLY_PAID',
                'PAID',
                'OVERDUE',
                'CANCELLED'
            )
        ),

    CONSTRAINT chk_invoices_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED')),

    CONSTRAINT chk_invoices_dates
        CHECK (due_date >= issue_date),

    CONSTRAINT chk_invoices_discount_percentage
        CHECK (discount_percentage BETWEEN 0 AND 100),

    CONSTRAINT chk_invoices_tax_percentage
        CHECK (tax_percentage BETWEEN 0 AND 100),

    CONSTRAINT chk_invoices_non_negative_amounts
        CHECK (
            subtotal >= 0
            AND discount_amount >= 0
            AND tax_amount >= 0
            AND total >= 0
            AND paid_amount >= 0
            AND balance >= 0
        ),

    CONSTRAINT chk_invoices_paid_not_over_total
        CHECK (paid_amount <= total),

    CONSTRAINT chk_invoices_balance
        CHECK (balance = total - paid_amount),

    CONSTRAINT chk_invoices_counts
        CHECK (total_items >= 0 AND total_quantity >= 0),

    CONSTRAINT chk_invoices_currency
        CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_invoices_cancellation
        CHECK (
            invoice_status <> 'CANCELLED'
            OR cancelled_at IS NOT NULL
        )
);

