CREATE VIEW invoice_payment_summary AS
SELECT
    i.id AS invoice_id,
    i.invoice_number,
    i.customer_id,
    i.invoice_status,
    i.currency,
    i.total,
    i.paid_amount,
    i.balance,
    COALESCE(
        SUM(p.amount) FILTER (WHERE p.payment_status = 'COMPLETED'),
        0
    ) AS recorded_payment_total,
    COUNT(p.id) FILTER (WHERE p.payment_status = 'COMPLETED') AS payment_count
FROM invoices i
LEFT JOIN payments p
    ON p.invoice_id = i.id
GROUP BY
    i.id,
    i.invoice_number,
    i.customer_id,
    i.invoice_status,
    i.currency,
    i.total,
    i.paid_amount,
    i.balance;

CREATE VIEW product_sales_summary AS
SELECT
    ii.product_id,
    ii.title,
    SUM(ii.quantity) AS quantity_sold,
    SUM(ii.discounted_total) AS net_sales
FROM invoice_items ii
JOIN invoices i
    ON i.id = ii.invoice_id
WHERE i.invoice_status IN ('ISSUED', 'PARTIALLY_PAID', 'PAID', 'OVERDUE')
GROUP BY
    ii.product_id,
    ii.title;

COMMENT ON VIEW invoice_payment_summary IS
    'Reconciliation view comparing stored invoice totals with completed payment rows.';

COMMENT ON VIEW product_sales_summary IS
    'Aggregated product sales used by dashboard and report queries.';

