-- Self-service login lives directly on customers: every Customer is created
-- through storefront registration, so email/password_hash are always present
-- (no separate customer_accounts table, no staff-created no-login customers).
CREATE TABLE customers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    first_name          VARCHAR(100),
    last_name           VARCHAR(100),
    company_name        VARCHAR(200),
    email               VARCHAR(255) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    phone               VARCHAR(30),
    tax_number          VARCHAR(100),

    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_customers_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED')),

    CONSTRAINT chk_customers_identity
        CHECK (
            NULLIF(BTRIM(first_name), '') IS NOT NULL
            OR NULLIF(BTRIM(last_name), '') IS NOT NULL
            OR NULLIF(BTRIM(company_name), '') IS NOT NULL
        )
);

CREATE INDEX idx_customers_name
    ON customers (last_name, first_name);

CREATE INDEX idx_customers_company_name
    ON customers (company_name);

CREATE INDEX idx_customers_status
    ON customers (status);

CREATE UNIQUE INDEX uq_customers_email_lower
    ON customers (LOWER(email));

CREATE INDEX idx_customers_phone
    ON customers (phone)
    WHERE phone IS NOT NULL;

CREATE UNIQUE INDEX uq_customers_tax_number
    ON customers (tax_number)
    WHERE tax_number IS NOT NULL;

CREATE TRIGGER trg_customers_set_updated_at
BEFORE UPDATE ON customers
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE customers IS
    'Individuals or businesses that receive invoices. Every row is a self-registered storefront login.';

