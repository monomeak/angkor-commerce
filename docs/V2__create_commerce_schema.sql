    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id              BIGINT NOT NULL,
    product_id              BIGINT,
    line_number             INTEGER NOT NULL,

    sku                     VARCHAR(100),
    title                   VARCHAR(200) NOT NULL,
    description             TEXT,
    thumbnail_url           TEXT,
    unit                    VARCHAR(50) NOT NULL DEFAULT 'piece',

    price                   NUMERIC(19, 4) NOT NULL,
    quantity                INTEGER NOT NULL,
    total                   NUMERIC(19, 4) NOT NULL,
    discount_percentage     NUMERIC(5, 2) NOT NULL DEFAULT 0,
    discounted_total        NUMERIC(19, 4) NOT NULL,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_invoice_items_invoice
        FOREIGN KEY (invoice_id)
        REFERENCES invoices (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_invoice_items_product
        FOREIGN KEY (product_id)
        REFERENCES products (id)
        ON DELETE SET NULL,

    CONSTRAINT uq_invoice_items_line
        UNIQUE (invoice_id, line_number),

    CONSTRAINT chk_invoice_items_line_number
        CHECK (line_number > 0),

    CONSTRAINT chk_invoice_items_price
        CHECK (price >= 0),

    CONSTRAINT chk_invoice_items_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_invoice_items_total
        CHECK (total = price * quantity),

    CONSTRAINT chk_invoice_items_discount_percentage
