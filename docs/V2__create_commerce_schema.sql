-- ---------------------------------------------------------------------------
-- Products
-- ---------------------------------------------------------------------------

-- Stock and sku deliberately do NOT live here — every product has at least
-- one row in product_variants (size = NULL for products with no size concept),
-- so variants are the single source of truth for both. No branching between
-- "does this product have variants or not" anywhere else in the codebase.
CREATE TABLE products (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                   VARCHAR(200) NOT NULL,
    description             TEXT,
    category_id             BIGINT NOT NULL,

    price                   NUMERIC(19, 4) NOT NULL,
    currency                CHAR(3) NOT NULL DEFAULT 'KHR',
    discount_percentage     NUMERIC(5, 2) NOT NULL DEFAULT 0,
    rating                  NUMERIC(3, 2) NOT NULL DEFAULT 0,

    unit                    VARCHAR(50) NOT NULL DEFAULT 'piece',
    thumbnail_url           TEXT,
    status                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_by_user_id      BIGINT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_products_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES users (id)
        ON DELETE SET NULL,

    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
        REFERENCES categories (id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_products_price
        CHECK (price >= 0),

    CONSTRAINT chk_products_discount_percentage
        CHECK (discount_percentage BETWEEN 0 AND 100),

    CONSTRAINT chk_products_rating
        CHECK (rating BETWEEN 0 AND 5),

    CONSTRAINT chk_products_currency
        CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_products_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

