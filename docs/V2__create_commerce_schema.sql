-- Self-referencing tree: Men / Women / Children are top-level rows (parent_id
-- IS NULL); each subcategory (T-Shirts, Boys, Boys > T-Shirts, ...) points to
-- its parent via parent_id. Supports any number of levels without new tables.
CREATE TABLE categories (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id           BIGINT,
    name                VARCHAR(150) NOT NULL,
    slug                VARCHAR(160) NOT NULL,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_categories_parent
        FOREIGN KEY (parent_id)
        REFERENCES categories (id)
        ON DELETE CASCADE,

    CONSTRAINT uq_categories_slug
        UNIQUE (slug),

    CONSTRAINT chk_categories_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED')),

    CONSTRAINT chk_categories_not_self_parent
        CHECK (parent_id IS DISTINCT FROM id)
);

CREATE INDEX idx_categories_parent_id
    ON categories (parent_id);

CREATE INDEX idx_categories_status
    ON categories (status);

CREATE TRIGGER trg_categories_set_updated_at
