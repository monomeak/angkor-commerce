-- ACME Invoice Management System
-- PostgreSQL initial database schema
-- Inspired by DummyJSON resource shapes while preserving real invoice-domain rules.
--
-- Target: PostgreSQL 15+
-- Naming: snake_case database columns, camelCase JSON fields in the API.
-- Money: NUMERIC instead of FLOAT/DOUBLE.
-- Time: TIMESTAMPTZ stored in UTC by PostgreSQL/JDBC.
--
-- Dashboard and report modules do not need tables because they aggregate data
-- from customers, products, invoices, invoice_items, and payments.

BEGIN;

-- ---------------------------------------------------------------------------
-- Shared updated_at trigger
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name          VARCHAR(100) NOT NULL,
    last_name           VARCHAR(100) NOT NULL,
    username            VARCHAR(100) NOT NULL,
    email               VARCHAR(255) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    phone               VARCHAR(30),
    image_url           TEXT,

    role                VARCHAR(30) NOT NULL DEFAULT 'STAFF',
    record_status       VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN ('SUPER_ADMIN', 'SHOP_ADMIN', 'STAFF', 'VIEWER')),

    CONSTRAINT chk_users_record_status
        CHECK (record_status IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

-- Case-insensitive uniqueness without requiring the PostgreSQL CITEXT extension.
CREATE UNIQUE INDEX uq_users_username_lower
    ON users (LOWER(username));

CREATE UNIQUE INDEX uq_users_email_lower
    ON users (LOWER(email));

CREATE INDEX idx_users_role
    ON users (role);

CREATE INDEX idx_users_record_status
    ON users (record_status);

CREATE TRIGGER trg_users_set_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE users IS
    'Application accounts used for authentication, authorization, ownership, and audit attribution.';

COMMENT ON COLUMN users.password_hash IS
    'Password hash only; never return this field through API responses.';

-- ---------------------------------------------------------------------------
-- Refresh tokens
-- ---------------------------------------------------------------------------

CREATE TABLE refresh_tokens (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL,
    token_hash              VARCHAR(255) NOT NULL,
    expires_at              TIMESTAMPTZ NOT NULL,
    revoked_at              TIMESTAMPTZ,
    replaced_by_token_id    BIGINT,
    created_by_ip           INET,
    revoked_by_ip           INET,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_refresh_tokens_replacement
        FOREIGN KEY (replaced_by_token_id)
        REFERENCES refresh_tokens (id)
        ON DELETE SET NULL,

    CONSTRAINT uq_refresh_tokens_token_hash
        UNIQUE (token_hash),

    CONSTRAINT chk_refresh_tokens_expiration
        CHECK (expires_at > created_at)
);

CREATE INDEX idx_refresh_tokens_user_id
    ON refresh_tokens (user_id);

CREATE INDEX idx_refresh_tokens_expires_at
    ON refresh_tokens (expires_at);

CREATE INDEX idx_refresh_tokens_active
    ON refresh_tokens (user_id, expires_at)
    WHERE revoked_at IS NULL;

COMMENT ON TABLE refresh_tokens IS
    'Hashed refresh tokens used for access-token renewal, rotation, and revocation.';

-- ---------------------------------------------------------------------------
-- Customers
-- ---------------------------------------------------------------------------

CREATE TABLE customers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_type       VARCHAR(20) NOT NULL DEFAULT 'INDIVIDUAL',

    first_name          VARCHAR(100),
    last_name           VARCHAR(100),
    company_name        VARCHAR(200),
    email               VARCHAR(255),
    phone               VARCHAR(30),
    tax_number          VARCHAR(100),

    record_status       VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_by_user_id  BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_customers_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES users (id)
        ON DELETE SET NULL,

    CONSTRAINT chk_customers_type
        CHECK (customer_type IN ('INDIVIDUAL', 'BUSINESS')),

    CONSTRAINT chk_customers_record_status
        CHECK (record_status IN ('ACTIVE', 'INACTIVE', 'DELETED')),

    CONSTRAINT chk_customers_identity
        CHECK (
            NULLIF(BTRIM(first_name), '') IS NOT NULL
            OR NULLIF(BTRIM(last_name), '') IS NOT NULL
            OR NULLIF(BTRIM(company_name), '') IS NOT NULL
        )
);

CREATE INDEX idx_customers_name
    ON customers (last_name, first_name);

CREATE INDEX idx_customers_company_name
    ON customers (company_name);

CREATE INDEX idx_customers_record_status
    ON customers (record_status);

CREATE INDEX idx_customers_email_lower
    ON customers (LOWER(email))
    WHERE email IS NOT NULL;

CREATE INDEX idx_customers_phone
    ON customers (phone)
    WHERE phone IS NOT NULL;

CREATE UNIQUE INDEX uq_customers_tax_number
    ON customers (tax_number)
    WHERE tax_number IS NOT NULL;

CREATE TRIGGER trg_customers_set_updated_at
BEFORE UPDATE ON customers
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE customers IS
    'Individuals or businesses that receive invoices.';

