FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE invoices IS
    'Invoice headers containing customer, lifecycle status, dates, denormalized totals, and payment balance.';

-- Invoice item values are snapshots. Product title, price, SKU, and thumbnail remain
-- unchanged even when the original product is later edited or removed.
CREATE TABLE invoice_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id              BIGINT NOT NULL,
    product_id              BIGINT,
    line_number             INTEGER NOT NULL,

    sku                     VARCHAR(100),
    title                   VARCHAR(200) NOT NULL,
    description             TEXT,
    thumbnail_url           TEXT,
    unit                    VARCHAR(50) NOT NULL DEFAULT 'piece',

    price                   NUMERIC(19, 4) NOT NULL,
    quantity                INTEGER NOT NULL,
    total                   NUMERIC(19, 4) NOT NULL,
    discount_percentage     NUMERIC(5, 2) NOT NULL DEFAULT 0,
    discounted_total        NUMERIC(19, 4) NOT NULL,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_invoice_items_invoice
        FOREIGN KEY (invoice_id)
        REFERENCES invoices (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_invoice_items_product
        FOREIGN KEY (product_id)
        REFERENCES products (id)
        ON DELETE SET NULL,

    CONSTRAINT uq_invoice_items_line
        UNIQUE (invoice_id, line_number),

    CONSTRAINT chk_invoice_items_line_number
        CHECK (line_number > 0),

    CONSTRAINT chk_invoice_items_price
        CHECK (price >= 0),

    CONSTRAINT chk_invoice_items_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_invoice_items_total
        CHECK (total = price * quantity),

    CONSTRAINT chk_invoice_items_discount_percentage
        CHECK (discount_percentage BETWEEN 0 AND 100),

    CONSTRAINT chk_invoice_items_discounted_total
        CHECK (
            discounted_total >= 0
            AND discounted_total <= total
        )
);

CREATE INDEX idx_invoice_items_invoice_id
    ON invoice_items (invoice_id);

CREATE INDEX idx_invoice_items_product_id
    ON invoice_items (product_id);

CREATE TRIGGER trg_invoice_items_set_updated_at
BEFORE UPDATE ON invoice_items
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE invoice_items IS
    'Immutable-style invoice line snapshots inspired by DummyJSON cart products.';

