-- ---------------------------------------------------------------------------
-- Payments (staff bookkeeping against invoices)
-- ---------------------------------------------------------------------------

-- Not a live payment transaction: no provider tracking, no pending/webhook lifecycle.
-- created_by (inherited) records who recorded the payment.
CREATE TABLE payments (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id              BIGINT NOT NULL,

    amount                  NUMERIC(19, 4) NOT NULL,
    currency                VARCHAR(3) NOT NULL DEFAULT 'KHR',
    payment_method          VARCHAR(30) NOT NULL,
    payment_status          VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    payment_date            DATE NOT NULL,

    reference_number        VARCHAR(150),
    notes                   TEXT,

    voided_at               TIMESTAMPTZ,
    void_reason             TEXT,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by              BIGINT,
    updated_by              BIGINT,

    CONSTRAINT fk_payments_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE RESTRICT,

    CONSTRAINT fk_payments_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_payments_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,

    CONSTRAINT chk_payments_amount CHECK (amount > 0),
    CONSTRAINT chk_payments_currency CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_payments_method
        CHECK (payment_method IN ('CASH', 'BANK_TRANSFER', 'QR_CODE', 'CARD', 'OTHER')),

    CONSTRAINT chk_payments_status
        CHECK (payment_status IN ('COMPLETED', 'VOIDED', 'REFUNDED')),

    CONSTRAINT chk_payments_voided
        CHECK (payment_status <> 'VOIDED' OR voided_at IS NOT NULL)
);

CREATE INDEX idx_payments_invoice_id ON payments (invoice_id);
CREATE INDEX idx_payments_payment_date ON payments (payment_date DESC);
CREATE INDEX idx_payments_payment_method ON payments (payment_method);
CREATE INDEX idx_payments_status ON payments (payment_status);
CREATE UNIQUE INDEX uq_payments_reference_number ON payments (reference_number) WHERE reference_number IS NOT NULL;

CREATE TRIGGER trg_payments_set_updated_at
BEFORE UPDATE ON payments
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE payments IS
    'Payment transactions recorded against invoices. Invoice paid_amount/balance/invoice_status must be updated in the same application transaction.';

