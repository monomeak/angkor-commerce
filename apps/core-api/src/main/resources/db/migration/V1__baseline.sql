FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE products IS
    'Sellable products with DummyJSON-inspired fields such as title, price, thumbnail. Stock/sku live on product_variants, not here.';

-- Every product has at least one row here: real size variants (S/M/L/...) get their
-- own row each, and a product with no size concept gets exactly one row with size = NULL.
CREATE TABLE product_variants (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT NOT NULL,
    size                VARCHAR(50),
    sku                 VARCHAR(100) NOT NULL,
    stock               INTEGER NOT NULL DEFAULT 0,
    price_override      NUMERIC(19, 4),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_product_variants_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,

    CONSTRAINT chk_product_variants_stock CHECK (stock >= 0),
    CONSTRAINT chk_product_variants_price_override CHECK (price_override IS NULL OR price_override >= 0)
);

CREATE UNIQUE INDEX uq_product_variants_sku ON product_variants (sku);

-- At most one sized row per (product, size)...
CREATE UNIQUE INDEX uq_product_variants_sized
    ON product_variants (product_id, size) WHERE size IS NOT NULL;

-- ...and at most one no-size row per product.
CREATE UNIQUE INDEX uq_product_variants_default
    ON product_variants (product_id) WHERE size IS NULL;

CREATE INDEX idx_product_variants_product_id ON product_variants (product_id);
CREATE INDEX idx_product_variants_low_stock ON product_variants (stock);

CREATE TRIGGER trg_product_variants_set_updated_at
BEFORE UPDATE ON product_variants
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE product_variants IS
    'Single source of truth for product stock and sku. size = NULL means the product has no size concept.';

