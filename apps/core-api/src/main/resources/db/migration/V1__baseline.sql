-- ---------------------------------------------------------------------------
-- Orders (storefront checkout — net new, no order_id FK on invoices yet)
-- ---------------------------------------------------------------------------

-- Created only at checkout; cart stays client-only. Shipping address is captured as
-- its own columns (matches customer-portal's ShippingAddress shape), not an FK to
-- a future customer_addresses table.
CREATE TABLE orders (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number            VARCHAR(50) NOT NULL,
    customer_id             BIGINT NOT NULL,

    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    shipping_full_name      VARCHAR(150) NOT NULL,
    shipping_phone          VARCHAR(30) NOT NULL,
    shipping_address        TEXT NOT NULL,
    shipping_city           VARCHAR(100) NOT NULL,
    shipping_postal_code    VARCHAR(30),
    shipping_notes          TEXT,

    subtotal                NUMERIC(19, 4) NOT NULL DEFAULT 0,
    shipping_fee            NUMERIC(19, 4) NOT NULL DEFAULT 0,
    total                   NUMERIC(19, 4) NOT NULL DEFAULT 0,
    currency                VARCHAR(3) NOT NULL DEFAULT 'KHR',

    placed_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,

    CONSTRAINT uq_orders_order_number UNIQUE (order_number),

    CONSTRAINT chk_orders_status CHECK (status IN ('PENDING', 'INVOICED', 'CANCELLED')),
    CONSTRAINT chk_orders_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_orders_non_negative_amounts
        CHECK (subtotal >= 0 AND shipping_fee >= 0 AND total >= 0)
);

CREATE INDEX idx_orders_customer_id ON orders (customer_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_placed_at ON orders (placed_at DESC);

CREATE TRIGGER trg_orders_set_updated_at
BEFORE UPDATE ON orders
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- Snapshots title/sku/unit_price_snapshot at order time so later Product price edits
-- never retroactively change a placed order (same pattern as invoice_items below).
-- product_variant_id is never null: every product has >= 1 variant, so checkout never
-- branches on "does this product have variants".
CREATE TABLE order_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT NOT NULL,
    product_id              BIGINT,
    product_variant_id      BIGINT NOT NULL,

    sku                     VARCHAR(100),
    title                   VARCHAR(200) NOT NULL,
    thumbnail_url           TEXT,

    unit_price_snapshot     NUMERIC(19, 4) NOT NULL,
    quantity                INTEGER NOT NULL,
    line_total              NUMERIC(19, 4) NOT NULL,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,

    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,

    CONSTRAINT fk_order_items_product_variant
        FOREIGN KEY (product_variant_id) REFERENCES product_variants (id) ON DELETE RESTRICT,

    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_items_unit_price_snapshot CHECK (unit_price_snapshot >= 0),
    CONSTRAINT chk_order_items_line_total CHECK (line_total >= 0)
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);
CREATE INDEX idx_order_items_product_id ON order_items (product_id);
CREATE INDEX idx_order_items_product_variant_id ON order_items (product_variant_id);

-- ---------------------------------------------------------------------------
-- Invoices (back-office billing)
-- ---------------------------------------------------------------------------

-- invoice_status is the billing lifecycle; status is the unrelated soft-delete flag
-- shared with other business records (same split as customers/categories/products).
CREATE TABLE invoices (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number          VARCHAR(50) NOT NULL,
    customer_id             BIGINT NOT NULL,

    invoice_status          VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    status                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    issue_date              DATE NOT NULL,
    due_date                DATE NOT NULL,

    subtotal                NUMERIC(19, 4) NOT NULL DEFAULT 0,
    discount_percentage     NUMERIC(5, 2) NOT NULL DEFAULT 0,
    discount_amount         NUMERIC(19, 4) NOT NULL DEFAULT 0,
    tax_percentage          NUMERIC(5, 2) NOT NULL DEFAULT 0,
    tax_amount              NUMERIC(19, 4) NOT NULL DEFAULT 0,
    total                   NUMERIC(19, 4) NOT NULL DEFAULT 0,
    paid_amount             NUMERIC(19, 4) NOT NULL DEFAULT 0,
    balance                 NUMERIC(19, 4) NOT NULL DEFAULT 0,

    currency                VARCHAR(3) NOT NULL DEFAULT 'KHR',
    total_items             INTEGER NOT NULL DEFAULT 0,
    total_quantity          INTEGER NOT NULL DEFAULT 0,

    notes                   TEXT,
    issued_at               TIMESTAMPTZ,
    cancelled_at            TIMESTAMPTZ,
    cancellation_reason     TEXT,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by              BIGINT,
    updated_by              BIGINT,

    CONSTRAINT fk_invoices_customer
        FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,

    CONSTRAINT fk_invoices_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_invoices_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,

    CONSTRAINT uq_invoices_invoice_number UNIQUE (invoice_number),

    CONSTRAINT chk_invoices_invoice_status
        CHECK (invoice_status IN ('DRAFT', 'ISSUED', 'PARTIALLY_PAID', 'PAID', 'OVERDUE', 'CANCELLED')),

    CONSTRAINT chk_invoices_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED')),
    CONSTRAINT chk_invoices_dates CHECK (due_date >= issue_date),
    CONSTRAINT chk_invoices_discount_percentage CHECK (discount_percentage BETWEEN 0 AND 100),
    CONSTRAINT chk_invoices_tax_percentage CHECK (tax_percentage BETWEEN 0 AND 100),

    CONSTRAINT chk_invoices_non_negative_amounts
        CHECK (
            subtotal >= 0
            AND discount_amount >= 0
            AND tax_amount >= 0
            AND total >= 0
            AND paid_amount >= 0
            AND balance >= 0
        ),

    CONSTRAINT chk_invoices_paid_not_over_total CHECK (paid_amount <= total),
    CONSTRAINT chk_invoices_balance CHECK (balance = total - paid_amount),
    CONSTRAINT chk_invoices_counts CHECK (total_items >= 0 AND total_quantity >= 0),
    CONSTRAINT chk_invoices_currency CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_invoices_cancellation
        CHECK (invoice_status <> 'CANCELLED' OR cancelled_at IS NOT NULL)
);

CREATE INDEX idx_invoices_customer_id ON invoices (customer_id);
CREATE INDEX idx_invoices_invoice_status ON invoices (invoice_status);
CREATE INDEX idx_invoices_issue_date ON invoices (issue_date DESC);
CREATE INDEX idx_invoices_due_date ON invoices (due_date);
CREATE INDEX idx_invoices_created_by ON invoices (created_by);
CREATE INDEX idx_invoices_recent ON invoices (created_at DESC);

CREATE INDEX idx_invoices_outstanding
    ON invoices (due_date, balance)
    WHERE invoice_status IN ('ISSUED', 'PARTIALLY_PAID', 'OVERDUE');

CREATE TRIGGER trg_invoices_set_updated_at
BEFORE UPDATE ON invoices
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- Line-item values are snapshots: title/price/sku/thumbnail stay unchanged even when
-- the source product is later edited or removed (product_id nullable, ON DELETE SET NULL).
CREATE TABLE invoice_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id              BIGINT NOT NULL,
    product_id              BIGINT,
    line_number             INTEGER NOT NULL,

    sku                     VARCHAR(100),
    title                   VARCHAR(200) NOT NULL,
    description             TEXT,
    thumbnail_url           TEXT,
    unit                    VARCHAR(50) NOT NULL DEFAULT 'piece',

    price                   NUMERIC(19, 4) NOT NULL,
    quantity                INTEGER NOT NULL,
    total                   NUMERIC(19, 4) NOT NULL,
    discount_percentage     NUMERIC(5, 2) NOT NULL DEFAULT 0,
    discounted_total        NUMERIC(19, 4) NOT NULL,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_invoice_items_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE,

    CONSTRAINT fk_invoice_items_product
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,

    CONSTRAINT uq_invoice_items_line UNIQUE (invoice_id, line_number),

    CONSTRAINT chk_invoice_items_line_number CHECK (line_number > 0),
    CONSTRAINT chk_invoice_items_price CHECK (price >= 0),
    CONSTRAINT chk_invoice_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_invoice_items_total CHECK (total = price * quantity),
    CONSTRAINT chk_invoice_items_discount_percentage CHECK (discount_percentage BETWEEN 0 AND 100),

    CONSTRAINT chk_invoice_items_discounted_total
        CHECK (discounted_total >= 0 AND discounted_total <= total)
